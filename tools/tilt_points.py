#!/usr/bin/env python3
"""Export decoded Open Brush control points to diagnostic PLY point clouds.

This is a geometry/coordinate diagnostic, NOT a reproduction of Open Brush
brush shaders. No per-stroke recentering: all points share their source space.
Usage: python3 tools/tilt_points.py voxen-strokes.json --output /tmp/tilt-points
"""
import argparse
import collections
import json
import math
from pathlib import Path

BRUSHES = {
    "6a1cf9f9-032c-45ec-9b1d-a6680bee30f7": "Dots",
    "70d79cca-b159-4f35-990c-f02193947fe8": "Smoke",
    "79348357-432d-4746-8e29-0e25c112e3aa": "MatteHull",
    "7136a729-1aab-bd24-f8b2-ca88b6adfb67": "NeonPulse",  # Verify against upstream registry before relying on this label.
}
# Only the three brush GUIDs verified against Open Brush material names.
BRUSHES.pop("7136a729-1aab-bd24-f8b2-ca88b6adfb67")


def byte_color(value):
    return max(0, min(255, round(float(value) * 255)))


def export_ply(path, points):
    with path.open("w", encoding="ascii") as out:
        out.write("ply\nformat ascii 1.0\n")
        out.write(f"element vertex {len(points)}\n")
        out.write("property float x\nproperty float y\nproperty float z\n")
        out.write("property uchar red\nproperty uchar green\nproperty uchar blue\n")
        out.write("property float pressure\nproperty uint stroke_id\nend_header\n")
        for p, color, pressure, stroke_id in points:
            out.write(f"{p[0]:.7g} {p[1]:.7g} {p[2]:.7g} "
                      f"{color[0]} {color[1]} {color[2]} "
                      f"{pressure:.7g} {stroke_id}\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("json", type=Path, help="JSON generated by inspect_tilt.py")
    parser.add_argument("--output", type=Path, default=Path("/tmp/tilt-points"))
    args = parser.parse_args()
    data = json.loads(args.json.read_text(encoding="utf-8"))
    args.output.mkdir(parents=True, exist_ok=True)
    groups = collections.defaultdict(list)
    all_points = []
    bounds_min = [math.inf] * 3
    bounds_max = [-math.inf] * 3
    for stroke_id, stroke in enumerate(data["strokes"]):
        guid = stroke["brush_guid"]
        color = tuple(byte_color(v) for v in stroke["color"][:3])
        for point in stroke["points"]:
            pos = point["position"]
            if len(pos) != 3 or not all(math.isfinite(v) for v in pos):
                raise ValueError(f"Invalid position in stroke {stroke_id}")
            for i in range(3):
                bounds_min[i] = min(bounds_min[i], pos[i])
                bounds_max[i] = max(bounds_max[i], pos[i])
            record = (pos, color, float(point["pressure"]), stroke_id)
            groups[guid].append(record)
            all_points.append(record)
    if not all_points:
        raise ValueError("No control points")
    export_ply(args.output / "all.ply", all_points)
    print(f"All: {len(all_points)} points, AABB {bounds_min} .. {bounds_max}")
    for guid, points in sorted(groups.items(), key=lambda item: -len(item[1])):
        label = BRUSHES.get(guid, guid[:8])
        path = args.output / f"{label}-{guid[:8]}.ply"
        export_ply(path, points)
        print(f"{label:12s} {len(points):6d} points -> {path}")
    print("Diagnostic only: point clouds omit brush geometry, textures, and shaders.")


if __name__ == "__main__":
    main()
